#!/usr/bin/env node
'use strict';

let fs;
try { fs = require('original-fs'); } catch (_) { fs = require('fs'); }
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const MARK = 'yapcord-stub';
const OLD_MARKS = ['yappermod-stub'];
const FUSE_SENTINEL = 'dL7pKGdnNz796PbbjQWNKmHXBZaB9tsX';
const FUSE_NAMES = ['RunAsNode', 'EnableCookieEncryption', 'EnableNodeOptionsEnvironmentVariable', 'EnableNodeCliInspectArguments', 'EnableEmbeddedAsarIntegrityValidation', 'OnlyLoadAppFromAsar'];

class PatchError extends Error {}

function readAsarFile(asarPath, innerPath) {
  const fd = fs.openSync(asarPath, 'r');
  try {
    const head = Buffer.alloc(16);
    fs.readSync(fd, head, 0, 16, 0);
    const headerSize = head.readUInt32LE(4);
    const jsonLen = head.readUInt32LE(12);
    if (head.readUInt32LE(0) !== 4 || jsonLen <= 0 || jsonLen > headerSize) throw new PatchError('This is not a valid .asar file: ' + asarPath);
    const json = Buffer.alloc(jsonLen);
    fs.readSync(fd, json, 0, jsonLen, 16);
    let node = JSON.parse(json.toString('utf8'));
    for (const part of innerPath.split('/')) {
      node = node && node.files && node.files[part];
      if (!node) return null;
    }
    if (node.files || node.unpacked) return null;
    const data = Buffer.alloc(node.size);
    fs.readSync(fd, data, 0, node.size, 8 + headerSize + Number(node.offset));
    return data;
  } finally {
    fs.closeSync(fd);
  }
}

function readFuses(exePath) {
  const fd = fs.openSync(exePath, 'r');
  try {
    const size = fs.fstatSync(fd).size;
    const needle = Buffer.from(FUSE_SENTINEL);
    const CHUNK = 8 * 1024 * 1024;
    const buf = Buffer.alloc(CHUNK + needle.length);
    for (let pos = 0; pos < size; pos += CHUNK) {
      const n = fs.readSync(fd, buf, 0, buf.length, pos);
      const at = buf.subarray(0, n).indexOf(needle);
      if (at >= 0) {
        const wire = Buffer.alloc(2 + FUSE_NAMES.length + 8);
        fs.readSync(fd, wire, 0, wire.length, pos + at + needle.length);
        const count = wire[1];
        const out = {};
        FUSE_NAMES.forEach((name, i) => {
          if (i >= count) return;
          const b = wire[2 + i];
          out[name] = b === 0x31 ? 'on' : b === 0x30 ? 'off' : 'removed';
        });
        return out;
      }
    }
    return null;
  } finally {
    fs.closeSync(fd);
  }
}

function findMainExe(installDir) {
  const exes = fs.readdirSync(installDir).filter((f) => /\.exe$/i.test(f) && !/uninstall|elevate|update/i.test(f));
  exes.sort((a, b) => fs.statSync(path.join(installDir, b)).size - fs.statSync(path.join(installDir, a)).size);
  return exes.length ? path.join(installDir, exes[0]) : null;
}

function findInstallDir(explicit, env = process.env) {
  const candidates = [];
  if (explicit) candidates.push(explicit);
  if (env.LOCALAPPDATA) {
    for (const n of ['yapper-desktop', 'Yapper', 'yapper']) candidates.push(path.join(env.LOCALAPPDATA, 'Programs', n));
  }
  for (const c of candidates) {
    if (fs.existsSync(path.join(c, 'resources', 'app.asar')) || fs.existsSync(path.join(c, 'resources', '_app.asar'))) return c;
  }
  throw new PatchError(
    explicit
      ? 'There is no resources\\app.asar in "' + explicit + '". Is this the folder of the Yapper app?'
      : 'Could not find the Yapper app. I looked in ' + path.join(env.LOCALAPPDATA || '%LOCALAPPDATA%', 'Programs') + '. Give the folder yourself: node tools\\yapper-patch.js install --dir "C:\\...\\yapper-desktop"',
  );
}

const STUB_INDEX = `// ${MARK}: generated by tools/yapper-patch.js. Starts YapCord, then Yapper's own app (resources/_app.asar) unchanged.
// Remove this folder and rename _app.asar back to app.asar to undo it (node tools/yapper-patch.js uninstall).
'use strict';
const path = require('path');
const fs = require('original-fs');
let switched = false;
let runtime = '';
try {
  const { app } = require('electron');
  runtime = path.join(app.getPath('appData'), 'YapCord', 'runtime');
  // An update that the Updater page downloaded earlier (runtime-next) becomes the runtime now, before anything of it is loaded.
  try {
    if (fs.existsSync(path.join(runtime + '-next', 'src', 'main', 'inject.js'))) {
      fs.rmSync(runtime + '-prev', { recursive: true, force: true });
      if (fs.existsSync(runtime)) fs.renameSync(runtime, runtime + '-prev');
      try {
        fs.renameSync(runtime + '-next', runtime);
        switched = true;
      } catch (err) {
        if (!fs.existsSync(runtime) && fs.existsSync(runtime + '-prev')) fs.renameSync(runtime + '-prev', runtime);
        throw err;
      }
    }
  } catch (err) {
    console.error('[YapCord] could not switch to the downloaded update:', err);
  }
  const inject = path.join(runtime, 'src', 'main', 'inject.js');
  if (fs.existsSync(inject)) {
    try {
      require(inject).install();
    } catch (err) {
      // A new version that does not start: go back to the one that worked, for the next start.
      if (switched && fs.existsSync(runtime + '-prev')) {
        try {
          fs.rmSync(runtime, { recursive: true, force: true });
          fs.renameSync(runtime + '-prev', runtime);
          console.error('[YapCord] the new version did not start; the previous version is back for the next start.');
        } catch (_) { /* nothing more to do */ }
      }
      throw err;
    }
  }
} catch (err) {
  console.error('[YapCord] could not start, starting Yapper without it:', err);
}
require(path.join(__dirname, '..', '_app.asar'));
`;

function stubPackageJson(original) {
  const keep = ['name', 'productName', 'version', 'description', 'author', 'homepage'];
  const out = {};
  for (const k of keep) if (original[k] !== undefined) out[k] = original[k];
  out.main = 'index.js';
  out.private = true;
  out[MARK] = true;
  return out;
}

function copyRuntime(sourceRoot, runtimeDir) {

  for (const extra of ['-next', '-prev']) fs.rmSync(runtimeDir + extra, { recursive: true, force: true });
  fs.rmSync(runtimeDir, { recursive: true, force: true });
  fs.mkdirSync(runtimeDir, { recursive: true });
  for (const name of ['src', 'themes', 'build', 'package.json', 'LICENSE', 'LICENSES']) {
    const from = path.join(sourceRoot, name);
    if (fs.existsSync(from)) fs.cpSync(from, path.join(runtimeDir, name), { recursive: true });
  }
}

function isStub(appDir) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(appDir, 'package.json'), 'utf8'));
    return pkg[MARK] === true || OLD_MARKS.some((m) => pkg[m] === true);
  } catch (_) {
    return false;
  }
}

const BUSY = new Set(['EBUSY', 'EPERM', 'EACCES']);
const busyMessage = 'Yapper is still running (also check the system tray next to the clock). Quit it completely (right-click the Yapper icon, then Quit) and try again.';

function install(o) {
  const say = o.log || (() => {});
  const res = path.join(o.installDir, 'resources');
  const asar = path.join(res, 'app.asar');
  const orig = path.join(res, '_app.asar');
  const appDir = path.join(res, 'app');

  if (fs.existsSync(appDir) && !isStub(appDir)) throw new PatchError('There is already an "app" folder in ' + res + ' that does not belong to YapCord. I am leaving it alone.');
  const exe = findMainExe(o.installDir);
  if (exe) {
    const fuses = readFuses(exe);
    if (fuses && (fuses.OnlyLoadAppFromAsar === 'on' || fuses.EnableEmbeddedAsarIntegrityValidation === 'on')) {
      throw new PatchError('This version of Yapper is protected against modification (Electron fuse ' + (fuses.OnlyLoadAppFromAsar === 'on' ? 'OnlyLoadAppFromAsar' : 'EnableEmbeddedAsarIntegrityValidation') + ' is on). This installer cannot do anything then.');
    }
    say(fuses ? 'Electron security check: ok.' : 'No Electron fuse block found in ' + path.basename(exe) + ' (ok).');
  }

  const source = fs.existsSync(asar) ? asar : orig;
  const pkgBytes = readAsarFile(source, 'package.json');
  if (!pkgBytes) throw new PatchError('There is no package.json in ' + source);
  const originalPkg = JSON.parse(pkgBytes.toString('utf8'));

  for (const dir of [path.join(o.appData, 'YapperMod', 'runtime'), path.join(o.appData, 'YapperMod', 'runtime-next'), path.join(o.appData, 'YapperMod', 'runtime-prev')]) {
    try {
      if (fs.existsSync(dir)) {
        fs.rmSync(dir, { recursive: true, force: true });
        say('Removed the old YapperMod files: ' + dir);
      }
    } catch (_) {  }
  }
  if (fs.existsSync(appDir) && isStub(appDir)) say('An older YapperMod/YapCord install was found. Removing it first, then installing the new version.');
  const runtimeDir = path.join(o.appData, 'YapCord', 'runtime');
  copyRuntime(o.sourceRoot, runtimeDir);
  say('YapCord files copied to ' + runtimeDir);

  let renamed = false;
  try {
    if (fs.existsSync(asar)) {

      if (fs.existsSync(orig)) fs.rmSync(orig, { force: true });
      fs.renameSync(asar, orig);
      renamed = true;
      const unpacked = asar + '.unpacked';
      if (fs.existsSync(unpacked)) {
        fs.rmSync(orig + '.unpacked', { recursive: true, force: true });
        fs.renameSync(unpacked, orig + '.unpacked');
      }
    }
    fs.rmSync(appDir, { recursive: true, force: true });
    fs.mkdirSync(appDir, { recursive: true });
    fs.writeFileSync(path.join(appDir, 'package.json'), JSON.stringify(stubPackageJson(originalPkg), null, 2));
    fs.writeFileSync(path.join(appDir, 'index.js'), STUB_INDEX);
  } catch (err) {

    try { fs.rmSync(appDir, { recursive: true, force: true }); } catch (_) {  }
    if (fs.existsSync(orig) && !fs.existsSync(asar)) {
      try { fs.renameSync(orig, asar); } catch (_) {  }
      try { if (fs.existsSync(orig + '.unpacked') && !fs.existsSync(asar + '.unpacked')) fs.renameSync(orig + '.unpacked', asar + '.unpacked'); } catch (_) {  }
    }
    if (err && BUSY.has(err.code)) throw new PatchError(busyMessage);
    throw err;
  }
  say('Done: Yapper now starts with YapCord inside.');
  return { runtimeDir, appDir, orig };
}

function uninstall(o) {
  const say = o.log || (() => {});
  const res = path.join(o.installDir, 'resources');
  const asar = path.join(res, 'app.asar');
  const orig = path.join(res, '_app.asar');
  const appDir = path.join(res, 'app');
  const hasStub = fs.existsSync(appDir) && isStub(appDir);
  if (fs.existsSync(appDir) && !hasStub) throw new PatchError('The "app" folder in ' + res + ' does not belong to YapCord. I am leaving it alone.');
  try {
    if (hasStub) fs.rmSync(appDir, { recursive: true, force: true });
    if (fs.existsSync(orig)) {
      if (fs.existsSync(asar)) fs.rmSync(orig, { force: true });
      else fs.renameSync(orig, asar);
      const unpacked = orig + '.unpacked';
      if (fs.existsSync(unpacked)) {
        if (fs.existsSync(asar + '.unpacked')) fs.rmSync(unpacked, { recursive: true, force: true });
        else fs.renameSync(unpacked, asar + '.unpacked');
      }
    }
  } catch (err) {
    if (err && BUSY.has(err.code)) throw new PatchError(busyMessage);
    throw err;
  }
  if (!fs.existsSync(asar)) throw new PatchError('There is no app.asar left in ' + res + '. Reinstall Yapper if it does not start.');
  say('YapCord has been removed from Yapper. Yapper is back to how it was.');
}

function status(o) {
  const res = path.join(o.installDir, 'resources');
  const patched = fs.existsSync(path.join(res, 'app')) && isStub(path.join(res, 'app')) && fs.existsSync(path.join(res, '_app.asar'));
  return { patched, installDir: o.installDir, runtime: fs.existsSync(path.join(o.appData, 'YapCord', 'runtime', 'src', 'main', 'inject.js')) };
}

function main(argv) {
  const cmd = argv[0];
  const i = argv.indexOf('--dir');
  const explicit = i >= 0 ? argv[i + 1] : '';
  const appData = process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming');
  const sourceRoot = path.join(__dirname, '..');
  const say = (s) => console.log(s);
  try {
    if (!['install', 'uninstall', 'status'].includes(cmd)) {
      say('Usage: node tools/yapper-patch.js install|uninstall|status [--dir "<Yapper folder>"]');
      return 2;
    }
    const installDir = findInstallDir(explicit);
    say('Found Yapper in ' + installDir);
    if (cmd === 'install') install({ installDir, sourceRoot, appData, log: say });
    else if (cmd === 'uninstall') uninstall({ installDir, appData, log: say });
    else say(JSON.stringify(status({ installDir, appData }), null, 2));
    return 0;
  } catch (err) {
    console.error('\nFailed: ' + (err instanceof PatchError ? err.message : (err && err.stack) || err));
    return 1;
  }
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { install, uninstall, status, findInstallDir, findMainExe, readAsarFile, readFuses, stubPackageJson, STUB_INDEX, MARK, PatchError };
